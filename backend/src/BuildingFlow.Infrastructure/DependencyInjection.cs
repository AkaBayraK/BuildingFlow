        services.AddSingleton<BuildingFlow.Application.IPaymentProviderAdapter>(provider => provider.GetRequiredService<SandboxPaymentProvider>());
        services.AddSingleton<PaymentProviderRegistry>();
        services.AddScoped<BuildingFlow.Application.IPaymentConfigurationStore, PaymentConfigurationStore>();
