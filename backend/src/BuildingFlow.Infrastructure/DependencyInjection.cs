        services.AddScoped<BuildingFlow.Application.IPublicWebsiteDomainStore, PublicWebsiteDomainStore>();
        services.AddScoped<BuildingFlow.Application.IWebsitePreviewStore, WebsitePreviewStore>();
        services.AddScoped<BuildingFlow.Application.IWebsiteStore, WebsiteStore>();
        services.AddScoped<BuildingFlow.Application.IPublicWebsiteStore, PublicWebsiteStore>();
        services.AddSingleton<BuildingFlow.Application.IFileStorage, S3FileStorage>();
